// commands/comply.ts — compliance grader for the bkit workflow suite.
//
// Grader:
//   - Pure functions over `git diff parentSha..HEAD` + filesystem state.
//   - Deterministic, advisory (NEVER gating). Fail-open: callers use the idiom
//     `pnpm bkit comply --phase={p} || echo "[bkit-comply] grader unavailable, skipping"`.
//   - Emits one `kind:"compliance"` row per run×rule into `.bkit/stats.jsonl`.
//   - Surfaces violations in ship-summary.md.
//
// Smallest-first rule set:
//   `no-mirror-edit`    — .claude/* and .cursor/* must not appear in the diff
//   `skip-ci-not-head`  — the HEAD commit must carry `[skip ci]` if the workflow
//                         close convention requires it (advisory only)
//
// See DE-34 for the shared-entrypoint + crash-isolation contract.

import { execFileSync } from "node:child_process";
import * as path from "node:path";
import { isMirrorPath } from "../shared/protected-paths.js";
import {
  gitEnv,
  resolveGitSha,
  type TelemetryEnvelope,
  type CompliancePayload,
} from "../ledgers/telemetry.js";
import { appendLedgerRows } from "./workflow/ledgers.js";
import type { ComplyPhase } from "../cli.js";

// ---------------------------------------------------------------------------
// Rule IDs
// ---------------------------------------------------------------------------

export type RuleId = "no-mirror-edit" | "skip-ci-not-head";

// ---------------------------------------------------------------------------
// Violation shape
// ---------------------------------------------------------------------------

export interface Violation {
  ruleId: RuleId;
  /** Human-readable description of what was found. */
  description: string;
  /** Relevant file path(s) or context. */
  evidence: string;
  /** "fail" | "n/a" — n/a means the rule did not apply (e.g. no commits to check). */
  result: "fail" | "n/a";
}

// ---------------------------------------------------------------------------
// Git helpers (pure wrappers — replaceable in tests)
// ---------------------------------------------------------------------------

export interface GitAdapter {
  /** Returns the diff stat paths (one per line, POSIX) for parentSha..head (HEAD by default). */
  diffPaths(parentSha: string, cwd: string, head?: string): string[];
  /** Returns the subject line of head (HEAD by default). */
  headSubject(cwd: string, head?: string): string;
}

/** SHA charset guard — only raw hex SHAs from the ledger are accepted. */
const SHA_RE = /^[0-9a-f]{7,40}$/;

export const realGitAdapter: GitAdapter = {
  diffPaths(parentSha: string, cwd: string, head = "HEAD"): string[] {
    if (!SHA_RE.test(parentSha) || (head !== "HEAD" && !SHA_RE.test(head))) {
      console.error(
        `[bkit-comply] diffPaths: "${parentSha}..${head}" is not a sha range — skipping diff`,
      );
      return [];
    }
    try {
      const output = execFileSync("git", ["diff", "--name-only", `${parentSha}..${head}`], {
        cwd,
        env: gitEnv(),
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
      return output
        .split("\n")
        .map((l) => l.trim())
        .filter(Boolean);
    } catch (e) {
      console.error("[bkit-comply] git diff failed (fail-open):", e);
      return [];
    }
  },

  headSubject(cwd: string, head = "HEAD"): string {
    if (head !== "HEAD" && !SHA_RE.test(head)) return "";
    try {
      return execFileSync("git", ["log", "-1", "--format=%s", head], {
        cwd,
        env: gitEnv(),
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch (e) {
      console.error("[bkit-comply] git log failed (fail-open):", e);
      return "";
    }
  },
};

// ---------------------------------------------------------------------------
// Individual rules (pure functions)
// ---------------------------------------------------------------------------

/**
 * no-mirror-edit — flags any path in the diff that falls inside a bkit-managed
 * mirror directory.  Mirror dirs must never be hand-edited; edits belong in the
 * canonical `.bkit/` source and are regenerated by `bkit install` / `bkit upgrade`.
 */
export function ruleNoMirrorEdit(diffPaths: readonly string[]): Violation | null {
  const mirrored = diffPaths.filter((p) => isMirrorPath(p));
  if (mirrored.length === 0) return null;
  return {
    ruleId: "no-mirror-edit",
    description:
      "One or more bkit-managed mirror files were hand-edited. " +
      "Mirror files must only be regenerated by `bkit install` / `bkit upgrade`, " +
      "not edited directly.",
    evidence: mirrored.join(", "),
    result: "fail",
  };
}

/**
 * skip-ci-not-head — advisory check that the final commit before ship does NOT
 * carry `[skip ci]` (which would leave the PR's statusCheckRollup empty and admit
 * a vacuously green PR).  Fires only for the `ship` phase.
 *
 * Advisory: a `[skip ci]` HEAD is legitimate for worktree-setup / create-pr commits
 * (DE-21 D2); the ship close step's CI-Dispatch Gate is the deterministic guard. This
 * rule adds a grader-level record.
 */
export function ruleSkipCiNotHead(headSubject: string, phase: string): Violation | null {
  if (phase !== "ship") return null;
  const hasSkipCi = headSubject.includes("[skip ci]");
  if (!hasSkipCi) return null;
  return {
    ruleId: "skip-ci-not-head",
    description:
      "HEAD commit carries `[skip ci]` at ship close. " +
      "This leaves the PR statusCheckRollup empty, admitting a vacuously green PR. " +
      "The CI-Dispatch Gate (#261) handles recovery, but this advisory records the occurrence.",
    evidence: `HEAD subject: ${headSubject}`,
    result: "fail",
  };
}

// ---------------------------------------------------------------------------
// Main grader entry point
// ---------------------------------------------------------------------------

export interface GraderInput {
  /** Git SHA of the parent commit (design-start / plan-start / etc.). */
  parentSha: string;
  /** The commit graded, when not HEAD: ship's squash. */
  headSha?: string;
  /** Workflow phase: design | plan | build | debug | ship */
  phase: string;
  /** Working directory for git commands. Defaults to process.cwd(). */
  cwd?: string;
  /** Inject a custom git adapter (for integration tests). */
  gitAdapter?: GitAdapter;
}

/**
 * Run all rules and return the Violation array.
 * Returns an empty array on any unexpected error (fail-open).
 */
export function runGrader(input: GraderInput): Violation[] {
  try {
    const cwd = input.cwd ?? process.cwd();
    const adapter = input.gitAdapter ?? realGitAdapter;
    const diffPaths = adapter.diffPaths(input.parentSha, cwd, input.headSha);
    const headSubject = adapter.headSubject(cwd, input.headSha);

    const violations: Violation[] = [];

    const noMirrorViolation = ruleNoMirrorEdit(diffPaths);
    if (noMirrorViolation) violations.push(noMirrorViolation);

    const skipCiViolation = ruleSkipCiNotHead(headSubject, input.phase);
    if (skipCiViolation) violations.push(skipCiViolation);

    return violations;
  } catch {
    // Fail-open: unhandled errors yield no violations rather than crashing.
    return [];
  }
}

// ---------------------------------------------------------------------------
// Row emitter — builds telemetry rows ready to append to .bkit/stats.jsonl
// ---------------------------------------------------------------------------

export interface ComplianceRowInput {
  violations: Violation[];
  /** The graded workflow (`by.workflow`). */
  workflow: string;
  /** The run's join key: HEAD at its close, shared with its counter and outcome rows. */
  parentSha: string;
  /** The step the grade ran at (`by.step`). */
  step: string;
}

/** A compliance row as handed to `bkit ledgers append`: no schema, ts, repo or bkit. */
export type ComplianceRowDraft = {
  kind: "compliance";
  by: { workflow: string; step: string };
} & CompliancePayload;

export type ComplianceRow = TelemetryEnvelope & CompliancePayload;

/**
 * Build one `kind:"compliance"` row per rule.
 * Rules that produced no violation emit a "pass" row.
 */
export function buildComplianceRows(input: ComplianceRowInput): ComplianceRowDraft[] {
  const { violations, workflow, parentSha, step } = input;

  const violationByRule = new Map<RuleId, Violation>();
  for (const v of violations) {
    violationByRule.set(v.ruleId, v);
  }

  const ALL_RULES: RuleId[] = ["no-mirror-edit", "skip-ci-not-head"];
  return ALL_RULES.map((ruleId) => {
    const violation = violationByRule.get(ruleId);
    const verdict: "pass" | "fail" | "n/a" = violation != null ? violation.result : "pass";
    const evidence = violation?.evidence;
    return {
      kind: "compliance",
      by: { workflow, step },
      run: { parentSha },
      rule: { id: ruleId, verdict, ...(evidence != null ? { evidence } : {}) },
    };
  });
}

// ---------------------------------------------------------------------------
// Append helper — writes rows to .bkit/stats.jsonl (best-effort)
// ---------------------------------------------------------------------------

/**
 * Append compliance rows to `<root>/.bkit/stats.jsonl` through `bkit ledgers append`.
 * Best-effort: prints `[bkit-comply] append failed: …` and returns false on error,
 * never throws.
 */
export function appendComplianceRows(
  rows: ComplianceRowDraft[],
  root: string,
  log: (m: string) => void = (m) => console.error(m),
): boolean {
  if (rows.length === 0) return false;
  try {
    appendLedgerRows(root, "stats", rows);
    return true;
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    log(`[bkit-comply] append failed: ${path.join(root, ".bkit", "stats.jsonl")} — ${msg}`);
    return false;
  }
}

// ---------------------------------------------------------------------------
// One grading pass, as `bkit workflows close` runs it before its report
// ---------------------------------------------------------------------------

/** The run a grade belongs to: the close's join key and step. */
export interface GradedRun {
  parentSha: string;
  step: string;
}

/**
 * Grade `phase` over HEAD~1..HEAD (HEAD alone in a one-commit repo) and append
 * its compliance rows to `<cwd>/.bkit/stats.jsonl`. With `squashSha` (ship's
 * close, run in the feature worktree) the squash commit is graded instead —
 * its subject and `squash~1..squash` — so the grade covers the whole feature
 * as it reaches main, not the worktree's last commit. The rows carry `run`'s
 * `parentSha` and step (default: HEAD and `close-gate`), so they join the
 * close's other rows. Fail-open: any error is logged and returns null, so a
 * close never stops on the grader.
 */
export function gradeCompliance(
  cwd: string,
  phase: string,
  log: (m: string) => void,
  squashSha?: string,
  run?: GradedRun,
): Violation[] | null {
  try {
    const squashParent = squashSha === undefined ? "" : resolveGitSha(`${squashSha}~1`, cwd);
    const base = squashParent || resolveGitSha("HEAD~1", cwd) || resolveGitSha("HEAD", cwd);
    if (!base) {
      log("[bkit-comply] cannot resolve a parent SHA (no commits?) — skipping grade");
      return null;
    }
    const headSha = squashParent ? squashSha : undefined;
    const violations = runGrader({ parentSha: base, phase, cwd, ...(headSha ? { headSha } : {}) });
    const rows = buildComplianceRows({
      violations,
      workflow: phase,
      parentSha: run?.parentSha ?? resolveGitSha("HEAD", cwd),
      step: run?.step ?? "close-gate",
    });
    appendComplianceRows(rows, cwd, log);
    log(
      violations.length > 0
        ? `[bkit-comply] Compliance violations found:\n${formatComplianceSummary(violations)}`
        : "[bkit-comply] All rules pass.",
    );
    return violations;
  } catch (err) {
    // Fail-open: the grader is advisory and never gates a close.
    log(`[bkit-comply] grader error (fail-open): ${(err as Error).message}`);
    return null;
  }
}

// ---------------------------------------------------------------------------
// Summarise violations for surfacing in ship-summary.md
// ---------------------------------------------------------------------------

/**
 * Format a human-readable compliance summary block for inclusion in
 * ship-summary.md.  Empty string when all rules pass.
 */
export function formatComplianceSummary(violations: Violation[]): string {
  if (violations.length === 0) return "";
  const lines = [
    "## Compliance Violations",
    "",
    ...violations.map(
      (v) => `- **${v.ruleId}** (${v.result}): ${v.description}\n  Evidence: ${v.evidence}`,
    ),
    "",
    "_Advisory — these violations are recorded in `.bkit/stats.jsonl` and do NOT block the workflow._",
  ];
  return lines.join("\n");
}

// comply — compliance grader (advisory, never gating, fail-open).
// Runs `runGrader` over `git diff parentSha..HEAD`, appends `kind:"compliance"`
// rows to `.bkit/stats.jsonl`, and logs violations.  Always exits 0 (fail-open);
// callers MUST use the pinned idiom:
//   `pnpm bkit comply --phase=<phase> || echo "[bkit-comply] grader unavailable, skipping"`
// See DE-34 for the shared-entrypoint + crash-isolation contract.
export function runComplyCommand(complyPhase: ComplyPhase | null): void {
  try {
    const cwd = process.cwd();
    const phase = complyPhase ?? "unknown";
    const logPrefix = "[bkit-comply]";

    // The grade's diff base MUST be a resolved hex SHA: diffPaths returns [] for anything
    // not matching /^[0-9a-f]{7,40}$/. Resolves HEAD~1, else HEAD; neither → skip the grade.
    const base = resolveGitSha("HEAD~1", cwd) || resolveGitSha("HEAD", cwd);
    if (!base) {
      console.log(`${logPrefix} cannot resolve a parent SHA (no commits?) — skipping grade`);
      return;
    }

    console.log(`${logPrefix} Running compliance grader (phase=${phase}, base=${base})`);

    const violations = runGrader({ parentSha: base, phase, cwd });
    // A row names the closing workflow it grades: without one, the grade is printed only.
    const rows =
      complyPhase === null
        ? []
        : buildComplianceRows({
            violations,
            workflow: complyPhase,
            parentSha: resolveGitSha("HEAD", cwd),
            step: "close-gate",
          });
    const written = complyPhase !== null && appendComplianceRows(rows, cwd);

    if (violations.length > 0) {
      const summary = formatComplianceSummary(violations);
      console.log(`${logPrefix} Compliance violations found:\n${summary}`);
    } else {
      console.log(`${logPrefix} All rules pass.`);
    }

    if (complyPhase === null) {
      console.log(`${logPrefix} no --phase: rows not written to .bkit/stats.jsonl.`);
    } else if (written) {
      console.log(
        `${logPrefix} Appended ${rows.length} compliance row(s) to .bkit/stats.jsonl (advisory — not gating).`,
      );
    }
  } catch (err: unknown) {
    // Fail-open: any unexpected error in the dispatch body must not gate the workflow.
    const msg = err instanceof Error ? err.message : String(err);
    console.error(`[bkit-comply] grader error (fail-open): ${msg}`);
  }
}
