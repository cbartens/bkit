// bkit-comply.ts — compliance grader for the bkit workflow suite.
//
// Grader:
//   - Pure functions over `git diff parentSha..HEAD` + filesystem state.
//   - Deterministic, advisory (NEVER gating). Fail-open: callers use the idiom
//     `pnpm bkit comply --phase={p} || echo "[bkit-comply] grader unavailable, skipping"`.
//   - Emits one `kind:"compliance"` row per run×rule into `.bkit/stats.jsonl`.
//   - Surfaces violations in ship-summary.md.
//
// Smallest-first rule set:
//   `no-mirror-edit`    — .claude/* and .cursor/* must not appear in the diff
//   `skip-ci-not-head`  — the HEAD commit must carry `[skip ci]` if the workflow
//                         close convention requires it (advisory only)
//
// See DE-34 for the shared-entrypoint + crash-isolation contract.

import { execFileSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import { isMirrorPath } from "./bkit-paths-policy.js";
import { type TelemetryEnvelope, type CompliancePayload } from "./bkit-telemetry.js";

// ---------------------------------------------------------------------------
// Rule IDs
// ---------------------------------------------------------------------------

export type RuleId = "no-mirror-edit" | "skip-ci-not-head";

// ---------------------------------------------------------------------------
// Violation shape
// ---------------------------------------------------------------------------

export interface Violation {
  ruleId: RuleId;
  /** Human-readable description of what was found. */
  description: string;
  /** Relevant file path(s) or context. */
  evidence: string;
  /** "fail" | "n/a" — n/a means the rule did not apply (e.g. no commits to check). */
  result: "fail" | "n/a";
}

// ---------------------------------------------------------------------------
// Git helpers (pure wrappers — replaceable in tests)
// ---------------------------------------------------------------------------

export interface GitAdapter {
  /** Returns the diff stat paths (one per line, POSIX) for parentSha..HEAD. */
  diffPaths(parentSha: string, cwd: string): string[];
  /** Returns the subject line of HEAD. */
  headSubject(cwd: string): string;
}

/** SHA charset guard — only raw hex SHAs from the ledger are accepted. */
const SHA_RE = /^[0-9a-f]{7,40}$/;

export const realGitAdapter: GitAdapter = {
  diffPaths(parentSha: string, cwd: string): string[] {
    if (!SHA_RE.test(parentSha)) {
      console.error(
        `[bkit-comply] diffPaths: parentSha "${parentSha}" does not match /^[0-9a-f]{7,40}$/ — skipping diff`,
      );
      return [];
    }
    try {
      const output = execFileSync("git", ["diff", "--name-only", `${parentSha}..HEAD`], {
        cwd,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
      return output
        .split("\n")
        .map((l) => l.trim())
        .filter(Boolean);
    } catch (e) {
      console.error("[bkit-comply] git diff failed (fail-open):", e);
      return [];
    }
  },

  headSubject(cwd: string): string {
    try {
      return execFileSync("git", ["log", "-1", "--format=%s"], {
        cwd,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch (e) {
      console.error("[bkit-comply] git log failed (fail-open):", e);
      return "";
    }
  },
};

// ---------------------------------------------------------------------------
// Individual rules (pure functions)
// ---------------------------------------------------------------------------

/**
 * no-mirror-edit — flags any path in the diff that falls inside a bkit-managed
 * mirror directory.  Mirror dirs must never be hand-edited; edits belong in the
 * canonical `.bkit/` source and are regenerated by `bkit install` / `bkit upgrade`.
 */
export function ruleNoMirrorEdit(diffPaths: readonly string[]): Violation | null {
  const mirrored = diffPaths.filter((p) => isMirrorPath(p));
  if (mirrored.length === 0) return null;
  return {
    ruleId: "no-mirror-edit",
    description:
      "One or more bkit-managed mirror files were hand-edited. " +
      "Mirror files must only be regenerated by `bkit install` / `bkit upgrade`, " +
      "not edited directly.",
    evidence: mirrored.join(", "),
    result: "fail",
  };
}

/**
 * skip-ci-not-head — advisory check that the final commit before ship does NOT
 * carry `[skip ci]` (which would leave the PR's statusCheckRollup empty and admit
 * a vacuously green PR).  Fires only for the `ship` phase.
 *
 * Advisory: a `[skip ci]` HEAD is legitimate for worktree-setup / create-pr commits
 * (DE-21 D2); the ship close step's CI-Dispatch Gate is the deterministic guard. This
 * rule adds a grader-level record.
 */
export function ruleSkipCiNotHead(headSubject: string, phase: string): Violation | null {
  if (phase !== "ship") return null;
  const hasSkipCi = headSubject.includes("[skip ci]");
  if (!hasSkipCi) return null;
  return {
    ruleId: "skip-ci-not-head",
    description:
      "HEAD commit carries `[skip ci]` at ship close. " +
      "This leaves the PR statusCheckRollup empty, admitting a vacuously green PR. " +
      "The CI-Dispatch Gate (#261) handles recovery, but this advisory records the occurrence.",
    evidence: `HEAD subject: ${headSubject}`,
    result: "fail",
  };
}

// ---------------------------------------------------------------------------
// Main grader entry point
// ---------------------------------------------------------------------------

export interface GraderInput {
  /** Git SHA of the parent commit (design-start / plan-start / etc.). */
  parentSha: string;
  /** Workflow phase: design | plan | build | debug | ship */
  phase: string;
  /** Absolute path to the plan file (currently unused; reserved for P2 rules). */
  planPath?: string;
  /** Working directory for git commands. Defaults to process.cwd(). */
  cwd?: string;
  /** Inject a custom git adapter (for integration tests). */
  gitAdapter?: GitAdapter;
}

/**
 * Run all rules and return the Violation array.
 * Returns an empty array on any unexpected error (fail-open).
 */
export function runGrader(input: GraderInput): Violation[] {
  try {
    const cwd = input.cwd ?? process.cwd();
    const adapter = input.gitAdapter ?? realGitAdapter;
    const diffPaths = adapter.diffPaths(input.parentSha, cwd);
    const headSubject = adapter.headSubject(cwd);

    const violations: Violation[] = [];

    const noMirrorViolation = ruleNoMirrorEdit(diffPaths);
    if (noMirrorViolation) violations.push(noMirrorViolation);

    const skipCiViolation = ruleSkipCiNotHead(headSubject, input.phase);
    if (skipCiViolation) violations.push(skipCiViolation);

    return violations;
  } catch {
    // Fail-open: unhandled errors yield no violations rather than crashing.
    return [];
  }
}

// ---------------------------------------------------------------------------
// Row emitter — builds telemetry rows ready to append to .bkit/stats.jsonl
// ---------------------------------------------------------------------------

export interface ComplianceRowInput {
  violations: Violation[];
  phase: string;
  parentSha: string;
  repo: string;
  bkitVersion: string;
  /** Additional envelope fields (step, subagent, etc.). */
  extra?: Partial<TelemetryEnvelope>;
}

export type ComplianceRow = TelemetryEnvelope & CompliancePayload;

/**
 * Build one `kind:"compliance"` row per rule.
 * Rules that produced no violation emit a "pass" row.
 * Every row carries `bkitVersion`.
 *
 * Called by the CLI dispatch after `runGrader`.
 */
export function buildComplianceRows(input: ComplianceRowInput): ComplianceRow[] {
  const ts = Date.now();
  const { violations, phase, parentSha, repo, bkitVersion, extra } = input;

  const violationByRule = new Map<RuleId, Violation>();
  for (const v of violations) {
    violationByRule.set(v.ruleId, v);
  }

  const ALL_RULES: RuleId[] = ["no-mirror-edit", "skip-ci-not-head"];
  const rows: ComplianceRow[] = [];

  for (const ruleId of ALL_RULES) {
    const violation = violationByRule.get(ruleId);
    const result: "pass" | "fail" | "n/a" = violation != null ? violation.result : "pass";
    const evidence = violation?.evidence;

    const envelope: TelemetryEnvelope = {
      ts: ts + rows.length, // micro-offset so each row has a unique ts within the batch
      kind: "compliance",
      repo,
      bkitVersion,
      workflow: phase,
      step: "close-gate",
      ...(extra ?? {}),
    };

    const payload: CompliancePayload = {
      rule: ruleId,
      result,
      ...(evidence != null ? { evidence } : {}),
      phase,
      parentSha,
    };

    rows.push({ ...envelope, ...payload });
  }

  return rows;
}

// ---------------------------------------------------------------------------
// Append helper — writes rows to .bkit/stats.jsonl (best-effort)
// ---------------------------------------------------------------------------

/**
 * Append compliance rows to the stats ledger.
 * Best-effort: prints `[bkit-comply] append failed: …` on error, never throws.
 */
export function appendComplianceRows(rows: ComplianceRow[], statsPath: string): void {
  try {
    const ndjson = rows.map((r) => JSON.stringify(r)).join("\n") + "\n";
    fs.appendFileSync(statsPath, ndjson, "utf8");
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error(`[bkit-comply] append failed: ${statsPath} — ${msg}`);
  }
}

// ---------------------------------------------------------------------------
// Summarise violations for surfacing in ship-summary.md
// ---------------------------------------------------------------------------

/**
 * Format a human-readable compliance summary block for inclusion in
 * ship-summary.md.  Empty string when all rules pass.
 */
export function formatComplianceSummary(violations: Violation[]): string {
  if (violations.length === 0) return "";
  const lines = [
    "## Compliance Violations",
    "",
    ...violations.map(
      (v) => `- **${v.ruleId}** (${v.result}): ${v.description}\n  Evidence: ${v.evidence}`,
    ),
    "",
    "_Advisory — these violations are recorded in `.bkit/stats.jsonl` and do NOT block the workflow._",
  ];
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// bkitVersion reader (used by CLI dispatch and tests)
// ---------------------------------------------------------------------------

/**
 * Read the bkit version from the package.json nearest to `searchFrom`.
 * Returns "0.0.0" on any read/parse error (fail-open).
 */
export function readBkitVersion(searchFrom?: string): string {
  try {
    // Walk up from searchFrom (or __dirname) looking for package.json with a
    // `version` field.  We stop at the filesystem root.
    let dir = path.resolve(searchFrom ?? path.join(__dirname, "../../.."));
    for (let i = 0; i < 8; i++) {
      const candidate = path.join(dir, "package.json");
      if (fs.existsSync(candidate)) {
        const pkg = JSON.parse(fs.readFileSync(candidate, "utf8")) as {
          version?: string;
        };
        if (typeof pkg.version === "string") return pkg.version;
      }
      const parent = path.dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  } catch (_e) {
    void _e; // fail-open: version read errors return default
  }
  return "0.0.0";
}
